-- init.sql — схема БД и первоначальное наполнение из CSV (db/seed/*.csv).
--
-- Postgres выполняет этот файл сам и ровно один раз — при первом старте с пустым томом (папка db/ подключена
-- в контейнер как /docker-entrypoint-initdb.d, см. compose.yaml). Дальше источник истины — PostgreSQL:
-- рестарты и пересборки файл не выполняют, правки CSV в уже наполненную базу не попадают.
-- Залить заново — только с пересозданием базы: docker compose down -v && docker compose up -d.
--
-- Всё в одной транзакции: если что-то упадёт, база останется пустой, а не наполовину наполненной.
--
-- Модель: продукт → операция → сервис. Главная сущность при вводе — сервис: запись (degradation_case)
-- ссылается только на service_id, а операция и продукт определяются сервисом. Новый сервис — новая строка
-- в service: дашборд и API берут сервисы из базы, в коде ничего менять не нужно.

BEGIN;


-- ============================================================================
-- Схема
-- ============================================================================

-- Системные справочники — через UI не меняются.

-- Группа столбцов в исходной таблице: «Деградация (без учета 5 минут)» / «(с учетом 5 минут)»
CREATE TABLE metric (
    id   int PRIMARY KEY,
    name text NOT NULL
);

-- Диапазон глубины деградации: «0-10%» … «91-100%» с шагом 10 — колонки таблицы «как в Excel».
-- Каждый случай деградации относится к одному из этих диапазонов (degradation_case.bucket_id)
CREATE TABLE bucket (
    id       int PRIMARY KEY,
    label    text NOT NULL,
    pct_from int  NOT NULL,
    pct_to   int  NOT NULL
);

-- Справочники и записи, которые можно будет добавлять и править через API (POST / PATCH / DELETE). У всех:
--   id — выдаёт база (BY DEFAULT: seed может указать id явно);
--   created_at, created_by — кто и когда создал строку; created_by обязателен — его пишет API (имя из токена
--     Keycloak), у строк из seed — 'seed'; значение по умолчанию 'seed' действует только на время загрузки CSV;
--   updated_at, updated_by — кто и когда менял последним; пустые, пока строку не меняли. updated_at ставит
--     триггер при любом UPDATE (и через API, и вручную), updated_by — API.
-- Названия не пустые и без дублей внутри своей группы — защита от двойного ввода.

-- Продукт: в нём операции, в операциях — сервисы
CREATE TABLE product (
    id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text        NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by text        NOT NULL DEFAULT 'seed',
    updated_at timestamptz,
    updated_by text,
    CONSTRAINT product_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT product_name_key UNIQUE (name)
);

CREATE TABLE operation (
    id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id int         NOT NULL REFERENCES product (id),
    num        int         NOT NULL,  -- столбец «№»
    name       text        NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by text        NOT NULL DEFAULT 'seed',
    updated_at timestamptz,
    updated_by text,
    CONSTRAINT operation_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT operation_product_name_key UNIQUE (product_id, name)
);

-- Сервис. Если на него есть записи, удалить его нельзя (не даст внешний ключ degradation_case.service_id) —
-- вместо удаления архив: is_active = false. Новую запись на архивный сервис API не примет,
-- но его история по-прежнему видна на дашборде
CREATE TABLE service (
    id           int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id int         NOT NULL REFERENCES operation (id),
    name         text        NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    created_by   text        NOT NULL DEFAULT 'seed',
    updated_at   timestamptz,
    updated_by   text,
    is_active    boolean     NOT NULL DEFAULT true,
    CONSTRAINT service_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT service_operation_name_key UNIQUE (operation_id, name)
);

-- Случай деградации сервиса. Глубина деградации — не точный процент, а диапазон с шагом 10
-- (bucket_id → «21-30%» и т.п.): авария определяется тем, в какой диапазон она попала.
-- case_date — день, когда случай произошёл (по нему дашборд показывает данные за выбранный месяц).
-- id — номер случая, его выдаёт только база (ALWAYS). Уникальности по сервису, метрике, диапазону и дате нет
-- намеренно: два одинаковых случая в один день — два разных случая с разными id (их видно в Excel, лист «Сырые данные»)
CREATE TABLE degradation_case (
    id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    service_id int         NOT NULL REFERENCES service (id),
    metric_id  int         NOT NULL REFERENCES metric (id),
    bucket_id  int         NOT NULL REFERENCES bucket (id),
    case_date  date        NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by text        NOT NULL DEFAULT 'seed',
    updated_at timestamptz,
    updated_by text
);

-- Индексы под частые запросы: случаи за период (дашборд), случаи сервиса и переходы по иерархии
CREATE INDEX degradation_case_case_date_idx  ON degradation_case (case_date);
CREATE INDEX degradation_case_service_id_idx ON degradation_case (service_id);
CREATE INDEX service_operation_id_idx        ON service (operation_id);
CREATE INDEX operation_product_id_idx        ON operation (product_id);

-- updated_at ставит сама база при любом UPDATE
CREATE FUNCTION touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END
$$;

CREATE TRIGGER product_touch_updated_at          BEFORE UPDATE ON product
    FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
CREATE TRIGGER operation_touch_updated_at        BEFORE UPDATE ON operation
    FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
CREATE TRIGGER service_touch_updated_at          BEFORE UPDATE ON service
    FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
CREATE TRIGGER degradation_case_touch_updated_at BEFORE UPDATE ON degradation_case
    FOR EACH ROW EXECUTE FUNCTION touch_updated_at();


-- ============================================================================
-- Первоначальное наполнение из CSV
-- ============================================================================

-- \copy — команда psql: читает файл и передаёт его в базу. Справочники приходят с готовыми id —
-- на них ссылаются строки других CSV.
--
-- Демо-данные случаев (degradation_case.csv) синтетические: октябрь 2026 — как в пример.xlsx (количество случаев
-- по диапазонам совпадает, даты — по 10 октября), остальные месяцы с сентября 2025 сгенерированы по его образцу.
-- Если случай длился дольше 5 минут, рядом стоит строка той же даты по метрике 2 («с учетом 5 минут»).

\copy metric (id, name) FROM '/docker-entrypoint-initdb.d/seed/metric.csv' WITH (FORMAT csv, HEADER true, ENCODING 'UTF8')
\copy bucket (id, label, pct_from, pct_to) FROM '/docker-entrypoint-initdb.d/seed/bucket.csv' WITH (FORMAT csv, HEADER true, ENCODING 'UTF8')
\copy product (id, name) FROM '/docker-entrypoint-initdb.d/seed/product.csv' WITH (FORMAT csv, HEADER true, ENCODING 'UTF8')
\copy operation (id, product_id, num, name) FROM '/docker-entrypoint-initdb.d/seed/operation.csv' WITH (FORMAT csv, HEADER true, ENCODING 'UTF8')
\copy service (id, operation_id, name) FROM '/docker-entrypoint-initdb.d/seed/service.csv' WITH (FORMAT csv, HEADER true, ENCODING 'UTF8')
\copy degradation_case (service_id, metric_id, bucket_id, case_date) FROM '/docker-entrypoint-initdb.d/seed/degradation_case.csv' WITH (FORMAT csv, HEADER true, ENCODING 'UTF8')

-- Seed загружен: дальше created_by без значения по умолчанию — API обязан указать пользователя
ALTER TABLE product          ALTER COLUMN created_by DROP DEFAULT;
ALTER TABLE operation        ALTER COLUMN created_by DROP DEFAULT;
ALTER TABLE service          ALTER COLUMN created_by DROP DEFAULT;
ALTER TABLE degradation_case ALTER COLUMN created_by DROP DEFAULT;

-- Счётчики id — после занятых seed-данными
SELECT setval(pg_get_serial_sequence('product', 'id'),   coalesce(max(id), 0) + 1, false) FROM product;
SELECT setval(pg_get_serial_sequence('operation', 'id'), coalesce(max(id), 0) + 1, false) FROM operation;
SELECT setval(pg_get_serial_sequence('service', 'id'),   coalesce(max(id), 0) + 1, false) FROM service;


COMMIT;
